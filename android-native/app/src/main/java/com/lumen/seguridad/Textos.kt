    private val mapas = mapOf("es" to es, "it" to it, "en" to en)

    fun idioma(context: Context): String {
        val guardado = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .getString(LANG, "") ?: ""
        if (guardado in IDIOMAS) return guardado
        val sys = Locale.getDefault().language.lowercase(Locale.ROOT).take(2)
        return if (sys in IDIOMAS) sys else "es"
    }

    fun t(context: Context, clave: String): String {
        val lang = idioma(context)
        return mapas[lang]?.get(clave) ?: es[clave] ?: clave
    }

    fun textos(lang: String): Map<String, String> = mapas[lang] ?: es
